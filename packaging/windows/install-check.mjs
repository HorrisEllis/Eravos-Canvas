#!/usr/bin/env node
// node packaging/windows/install-check.mjs <stage folder> <out .nsh> — what the Setup checks after it has written the app (3.207).
// His words, 2026-11-21: "update broke my eravos." The ERAVOS.exe he sent was 39,796,736 bytes of a 246 MB program: the install stopped
// half way through writing it and nothing noticed — the update said nothing, ERAVOS would not start. Now every file of 256 KB or more is
// listed here with its size; eravos.nsi checks each one on disk after writing (a missing or short file = the install failed, said so, and
// the version is not written, so ERAVOS Update.exe sees it and offers to run the Setup again).
import fs from 'fs'; import path from 'path';
const [stage, out] = process.argv.slice(2); if (!stage || !out) { console.error('usage: install-check.mjs <stage> <out.nsh>'); process.exit(2); }
const MIN = 256 * 1024, rows = [];
(function walk(dir) { for (const e of fs.readdirSync(dir, { withFileTypes: true })) { const p = path.join(dir, e.name);
  if (e.isDirectory()) walk(p); else { const s = fs.statSync(p).size; if (s >= MIN) rows.push([path.relative(stage, p).split(path.sep).join('\\'), s]); } } })(stage);
rows.sort((a, b) => b[1] - a[1]);
if (!rows.some(r => r[0] === 'ERAVOS.exe')) { console.error('install-check: no ERAVOS.exe in ' + stage); process.exit(1); }
fs.writeFileSync(out, '; generated by packaging/windows/install-check.mjs — do not edit\n' + rows.map(([f, s]) => `!insertmacro CheckFile "${f}" ${s}`).join('\n') + '\n');
console.log('install-check:', rows.length, 'files checked after install →', out);
