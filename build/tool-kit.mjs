#!/usr/bin/env node
/* Completes every tool folder so it travels on its own — node build/tool-kit.mjs [--thumbs-all]
 * Reads each tool's real definition from the running page (headless Chromium) and writes, per folder:
 *   packs/pack.schema.json   what a pack for THIS tool may contain: every param with its type, range, options
 *                            (validate.mjs checks every pack.json in the folder against it)
 *   tool.json works_with     tools it can be wired to, computed from both sides' ports (audio → audio, json → json…)
 *   tool.json conflicts      kept as written by hand (never computed)
 *   <tool>.test.js           created once if missing: the shared tool contract + room for the tool's own tests
 *   preview.png              thumbnail, rendered only when missing (or all with --thumbs-all)
 * Order for a new tool: build/new-tool.mjs → build/index-tools.mjs (so the page loads it) → this → build/validate.mjs. */
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
import { chromium } from '../host/driver/glass.js';   // Clear Glass's driver, not Playwright (his call, 2026-10-21)
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), DOM = path.join(ROOT, 'tools');
const ALL_THUMBS = process.argv.includes('--thumbs-all');
const folders = [];
for (const d of fs.readdirSync(DOM)) { const t = path.join(DOM, d, 'tools'); if (!fs.existsSync(t)) continue;
  for (const c of fs.readdirSync(t)) { const cd = path.join(t, c); if (!fs.statSync(cd).isDirectory()) continue;
    for (const n of fs.readdirSync(cd)) { const td = path.join(cd, n), mj = path.join(td, 'tool.json'); if (fs.existsSync(mj)) folders.push({ dir: td, name: n, m: JSON.parse(fs.readFileSync(mj, 'utf8')) }); } } }

const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const p = await b.newPage({ viewport: { width: 1500, height: 1200 }, deviceScaleFactor: 2 });   // 2×: card pictures stay sharp on hi-dpi screens
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.addInitScript(() => { window.ERAVOS_CATALOG_ALL = true; });   // P41 catalog: a fresh profile installs no tools — this script needs every one
await p.goto('file://' + ROOT + '/canvas/index.html?noboot'); await p.waitForFunction(() => window.OrganismFactory && window.Shell && window.Shell.X, null, { timeout: 30000 });
const defs = await p.evaluate(() => Object.fromEntries(OrganismFactory.defined().map(d => [d.id, {
  label: d.label, config: (d.config || []).map(c => ({ key: c.key, type: c.type, min: c.min, max: c.max, options: c.options, hidden: !!c.hidden })),
  hooks: (d.hooks || []).map(h => ({ id: h.hook_id, dir: h.direction, wire: h.wire_type, type: h.data_type || h.event_type || null, accepts: h.accepts || null })),
}])));

// ---- what can be wired to what: same wire type, opposite direction; dataflow also checks the value type
const fits = (o, i) => o.wire === i.wire && (o.wire !== 'dataflow' || !i.accepts || i.accepts.includes('*') || i.accepts.includes(o.type));
const outs = (id) => defs[id].hooks.filter(h => h.dir === 'out' || h.dir === 'inout'), ins = (id) => defs[id].hooks.filter(h => h.dir === 'in' || h.dir === 'inout');
const SKIP_WIRES = new Set(['event_bus']); // the bus reaches everyone — listing it would say "works with everything"
function worksWith(id) {
  const set = new Set();
  for (const other of Object.keys(defs)) { if (other === id || other.startsWith('test.')) continue;
    if (outs(id).some(o => !SKIP_WIRES.has(o.wire) && ins(other).some(i => fits(o, i))) || outs(other).some(o => !SKIP_WIRES.has(o.wire) && ins(id).some(i => fits(o, i)))) set.add(other); }
  return [...set].sort();
}
function paramSchema(c) {
  if (c.type === 'number') return Object.assign({ type: 'number' }, c.min !== undefined ? { minimum: c.min } : {}, c.max !== undefined ? { maximum: c.max } : {});
  if (c.type === 'integer') return Object.assign({ type: 'integer' }, c.min !== undefined ? { minimum: c.min } : {}, c.max !== undefined ? { maximum: c.max } : {});
  if (c.type === 'boolean') return { type: 'boolean' };
  if (c.type === 'enum') return { enum: c.options };
  if (c.type === 'string') return { type: 'string' };
  return {};
}
let nSchema = 0, nTests = 0, nThumbs = 0, nWorks = 0;
for (const f of folders) {
  const d = defs[f.m.id]; if (!d) { console.error('✗ not defined in the page: ' + f.m.id); continue; }
  // 1. pack schema
  const pd = path.join(f.dir, 'packs'); fs.mkdirSync(pd, { recursive: true });
  const params = Object.fromEntries(d.config.map(c => [c.key, paramSchema(c)]));
  const schema = {
    $schema: 'https://json-schema.org/draft/2020-12/schema', $id: `${f.m.id}/packs/pack.schema.json`,
    title: `Packs for ${d.label} — GENERATED by build/tool-kit.mjs from the tool's params (do not edit)`,
    description: 'A pack.json in this folder is an eravos.pack/1 (schemas/pack.schema.json) whose items for this tool match the shape below.',
    tool: f.m.id,
    properties: { items: { type: 'object', properties: { [f.m.id]: { type: 'object', properties: { presets: { type: 'object', additionalProperties: {
      type: 'object', properties: { params: { type: 'object', properties: params, additionalProperties: false }, extra: { type: 'object' }, assets: { type: 'array', items: { type: 'string' } }, label: { type: 'string' }, tags: { type: 'array', items: { type: 'string' } } }, additionalProperties: false } } } } } } },
  };
  fs.writeFileSync(path.join(pd, 'pack.schema.json'), JSON.stringify(schema, null, 2) + '\n'); nSchema++;
  // 2. relations
  f.m.works_with = worksWith(f.m.id); nWorks += f.m.works_with.length;
  if (!Array.isArray(f.m.conflicts)) f.m.conflicts = [];
  // 3. tests
  const tf = f.name + '.test.js';
  if (!fs.existsSync(path.join(f.dir, tf))) {
    fs.writeFileSync(path.join(f.dir, tf), `/* ${d.label} (${f.m.id}) — tests that travel with the tool. The contract is shared (tests/harness.js
 * TH.toolContract): spawns clean, every shipped preset loads in range, save → load is exact, closing leaves nothing behind,
 * Stop all is obeyed. Add this tool's own tests below it. */
TH.toolContract('${f.m.id}');
`); nTests++;
  }
  f.m.files.tests = tf;
  // 4. pictures: preview.png = the whole window (detail pane) · thumb.png = its main display cropped 16:10 (the ＋ Add card)
  const needPreview = ALL_THUMBS || !f.m.files.preview || !/\.png$/.test(f.m.files.preview) || !fs.existsSync(path.join(f.dir, f.m.files.preview));
  const needThumb = ALL_THUMBS || !f.m.files.thumb || !fs.existsSync(path.join(f.dir, f.m.files.thumb));
  if (needPreview || needThumb) {
    const inst = await p.evaluate((id) => { Shell.activate(); const dm = (OrganismFactory.def(id).domain); try { Shell.X.enterMode(Shell.X.modes().find(m => m.domain === dm).id); } catch (e) {} OrganismFactory.clearAll(Kernel); CanvasWM.view = { x: 0, y: 0, z: 1 }; CanvasWM.applyView(); const i = OrganismFactory.spawn(id, { x: 30, y: 20 }); try { Kernel.bus.publish('ui:audition:' + i, { note: 57, velocity: 0.9, duration: 1.5 }); } catch (e) {} return i; }, f.m.id);
    await p.waitForTimeout(900);
    const el = inst && await p.$(`.wm-win[data-instance="${inst}"]`);
    if (!el) console.error('✗ no window to photograph: ' + f.m.id);
    else {
      if (needPreview) { const old = f.m.files.preview; await el.screenshot({ path: path.join(f.dir, 'preview.png') }); if (old && old !== 'preview.png') fs.rmSync(path.join(f.dir, old), { force: true }); f.m.files.preview = 'preview.png'; nThumbs++; }
      if (needThumb) {
        // the hero: the biggest canvas in the window (orb, lattice, spectrum, grid…); none → the window body under its title bar
        const box = await p.evaluate((i) => {
          const w = document.querySelector(`.wm-win[data-instance="${i}"]`), wr = w.getBoundingClientRect();
          let best = null; w.querySelectorAll('canvas').forEach(c => { const r = c.getBoundingClientRect(); if (r.width * r.height > (best ? best.width * best.height : 6000)) best = r; });
          const head = w.querySelector('.wm-head, header'), top = head ? head.getBoundingClientRect().bottom : wr.top;
          const r = best || { left: wr.left, top, width: wr.width, height: wr.bottom - top };
          // grow to 16:10 around the hero, kept inside the window
          let W = r.width, H = r.height; if (W / H > 1.6) H = W / 1.6; else W = H * 1.6;
          W = Math.min(W, wr.width); H = Math.min(H, W / 1.6, wr.bottom - top); W = Math.min(W, H * 1.6);
          const cx = r.left + r.width / 2, cy = r.top + r.height / 2;
          const x = Math.max(wr.left, Math.min(wr.right - W, cx - W / 2)), y = Math.max(top, Math.min(wr.bottom - H, cy - H / 2));
          return { x, y, width: W, height: H };
        }, inst);
        await p.screenshot({ path: path.join(f.dir, 'thumb.png'), clip: box }); f.m.files.thumb = 'thumb.png';
      }
    }
    await p.evaluate((i) => i && OrganismFactory.close(i), inst);
  }
  fs.writeFileSync(path.join(f.dir, 'tool.json'), JSON.stringify(f.m, null, 2) + '\n');
}
await b.close();
if (errs.length) console.error('page errors:\n' + errs.slice(0, 10).join('\n'));
console.log(`${folders.length} tools · ${nSchema} pack schemas · ${nWorks} works-with links · ${nTests} new test files · ${nThumbs} thumbnails`);
