#!/usr/bin/env node
/* The dependency graph of the next phases, read from the specs (his ask, 2026-11-05: "start bottom up, then the highest leverage.
 * use a dependancy graph"). Nothing here is hand-kept: change a spec, run this again.
 *   tools/music/planned/*.spec         a planned tool: its `assembles` line names the components it stands on; its family
 *   tools/music/components/<id>/       a component: <id>.spec (its `used by`), and <id>.js when it is BUILT
 *   specs/eravos.music-ecosystem.spec  §13 development_phases: which tools each phase ships
 * Leverage of a component = how many planned tools stand on it. A tool is READY when every component it assembles is built.
 * Bottom-up order: phase by phase, the components that phase's tools still need, most leverage first; then the tools it unlocks.
 *   node build/eco-graph.mjs [--out docs/eco-graph.md] [--json]   */
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = (k, d) => { const i = process.argv.indexOf(k); return i >= 0 ? process.argv[i + 1] : d; };
const OUT = arg('--out', 'docs/eco-graph.md');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

// ---- components
const CDIR = 'tools/music/components';
const comps = new Map();
for (const id of fs.readdirSync(path.join(ROOT, CDIR)).sort()) {
  const dir = path.join(CDIR, id); if (!fs.statSync(path.join(ROOT, dir)).isDirectory()) continue;
  const spec = fs.existsSync(path.join(ROOT, dir, id + '.spec')) ? read(path.join(dir, id + '.spec')) : '';
  const usedBy = ((/^used by:\s*(.+)$/m.exec(spec) || [])[1] || '').split('·').map(s => s.trim()).filter(Boolean);
  const group = ((/group:\s*([\w-]+)/.exec(spec) || [])[1]) || '';
  const job = ((/job:\s*(.+)$/m.exec(spec) || [])[1] || '').trim();
  const built = fs.existsSync(path.join(ROOT, dir, id + '.js'));
  comps.set(id, { id, group, job, usedBy, built, tools: new Set() });
}
// ---- planned tools
const TDIR = 'tools/music/planned';
const tools = new Map();
for (const f of fs.readdirSync(path.join(ROOT, TDIR)).filter(f => f.endsWith('.spec')).sort()) {
  const s = read(path.join(TDIR, f)), id = f.replace(/\.spec$/, '');
  const m = /^assembles[^\n]*\n\s+([^\n]+)/m.exec(s); if (!m) continue;   // older specs without the template: not in the graph
  const needs = m[1].split('·').map(x => x.trim()).filter(Boolean);
  const family = ((/family:\s*([\w-]+)/.exec(s) || [])[1]) || '';
  const status = ((/status\s+([^\s·]+)/.exec(s.split('\n')[0]) || [])[1]) || '';
  const label = ((/label:\s*([^;]+);/.exec(s) || [])[1] || id).trim();
  tools.set(id, { id, label, family, status, needs, phase: null });
  needs.forEach(c => { if (comps.has(c)) comps.get(c).tools.add(id); });
}
// ---- phases (§13)
const eco = read('specs/eravos.music-ecosystem.spec');
const phases = [];
const ph = eco.slice(eco.indexOf('development_phases:'));
for (const m of ph.matchAll(/^  (phase_\d+_[\w]+):\n([\s\S]*?)(?=^  phase_|\n# =+)/gm)) {
  const name = m[1], body = m[2], list = ((/tools:\s*\[([^\]]*)\]/.exec(body) || [])[1] || '').split(',').map(s => s.trim()).filter(Boolean);
  const obj = ((/objective:\s*"?([^"\n]+)/.exec(body) || [])[1] || '').trim();
  phases.push({ name, objective: obj, tools: list });
  list.forEach(t => { if (tools.has(t) && tools.get(t).phase === null) tools.get(t).phase = name; });
}
const missingComp = new Set(); tools.forEach(t => t.needs.forEach(c => { if (!comps.has(c)) missingComp.add(c); }));
const lev = (c) => comps.get(c) ? comps.get(c).tools.size : 0;
const ready = (t) => t.needs.every(c => comps.get(c) && comps.get(c).built);
const builtN = [...comps.values()].filter(c => c.built).length;

// ---- the bottom-up order: per phase, its tools' unbuilt components by leverage, then those tools
const done = new Set([...comps.values()].filter(c => c.built).map(c => c.id)), order = [];
for (const p of phases) {
  const ts = p.tools.map(t => tools.get(t)).filter(Boolean);
  const need = [...new Set(ts.flatMap(t => t.needs))].filter(c => comps.has(c) && !done.has(c)).sort((a, b) => lev(b) - lev(a) || a.localeCompare(b));
  need.forEach(c => done.add(c));
  order.push({ phase: p, components: need, tools: ts.map(t => t.id), unplanned: p.tools.filter(t => !tools.has(t)) });
}
const rest = [...comps.values()].filter(c => !done.has(c.id) && c.tools.size).sort((a, b) => lev(b.id) - lev(a.id));

if (process.argv.includes('--json')) { console.log(JSON.stringify({ comps: [...comps.values()].map(c => ({ ...c, tools: [...c.tools] })), tools: [...tools.values()], order }, null, 1)); process.exit(0); }
const top = [...comps.values()].sort((a, b) => lev(b.id) - lev(a.id) || a.id.localeCompare(b.id));
const md = [
  '# The next phases as a dependency graph', '',
  'Generated by `node build/eco-graph.mjs` from the specs (planned tools\' `assembles`, components\' specs, the ecosystem\'s §13 phases).',
  'Bottom up: a tool is built once every component it stands on is built. Highest leverage first: the component the most tools stand on.', '',
  `**${comps.size} components** (${builtN} built) · **${tools.size} planned tools** in the graph (${[...tools.values()].filter(ready).length} ready to build today)` +
  (missingComp.size ? ` · named by a tool but without a component spec: ${[...missingComp].join(', ')}` : ''), '',
  '## Components by leverage (how many planned tools stand on each)', '', '| component | group | tools on it | built |', '|---|---|---|---|',
  ...top.filter(c => c.tools.size).map(c => `| ${c.id} | ${c.group} | ${c.tools.size} | ${c.built ? '✓' : ''} |`), '',
  '## The order, phase by phase', '',
  ...order.flatMap(o => [`### ${o.phase.name.replace(/_/g, ' ')}`, o.phase.objective ? `_${o.phase.objective}_` : '', '',
    o.components.length ? '**Build first (components, most leverage first):** ' + o.components.map(c => `${c} (${lev(c)})`).join(' · ') : '**Components:** none new — everything it needs is built or comes from an earlier phase',
    '', o.tools.length ? '**Then these tools (each shown to him as a UI preview first):** ' + o.tools.join(' · ') : '', o.unplanned.length ? `_Named in §13 but no tool spec yet: ${o.unplanned.join(', ')}_` : '', '']),
  rest.length ? '### Components no phase calls for yet (used by tools outside §13\'s lists)' : '', rest.length ? rest.map(c => `${c.id} (${c.tools.size})`).join(' · ') : '', '',
].join('\n');
fs.writeFileSync(path.join(ROOT, OUT), md);
console.log(`${comps.size} components (${builtN} built) · ${tools.size} tools · ${phases.length} phases → ${OUT}`);
console.log('top leverage: ' + top.slice(0, 10).map(c => `${c.id} ${c.tools.size}${c.built ? '✓' : ''}`).join(' · '));
order.forEach(o => console.log(`${o.phase.name}: ${o.components.length} components, ${o.tools.length} tools${o.unplanned.length ? ', ' + o.unplanned.length + ' without spec' : ''}`));
