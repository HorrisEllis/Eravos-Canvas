#!/usr/bin/env node
// node build/domain-specs.mjs — writes one spec per mapped tool, one per domain, and the map of every domain.
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
import { PORTS, DOMAINS } from '../specs/src/domains.mjs';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), OUT = path.join(ROOT, 'specs');
// P37: built tools are the folders that have a tool.json; a mapped tool's spec lives in tools/<d>/planned/ until it is built
const builtIn = (dom) => { const t = path.join(ROOT, 'tools', dom, 'tools'); return fs.existsSync(t) ? fs.readdirSync(t).flatMap(c => fs.statSync(path.join(t, c)).isDirectory() ? fs.readdirSync(path.join(t, c)).filter(x => fs.existsSync(path.join(t, c, x, 'tool.json'))) : []) : []; };
const music = builtIn('music');
const list = (a) => a.length ? a.map(x => '    - ' + x).join('\n') : '    - (none)';
let n = 0;
for (const D of DOMAINS) {
  const done = new Set(builtIn(D.id)), PL = path.join(ROOT, 'tools', D.id, 'planned'); fs.mkdirSync(PL, { recursive: true });
  for (const [id, label, icon, purpose, ins, outs, params, behave, test, works] of D.tools) {
    if (done.has(id)) { fs.rmSync(path.join(PL, id + '.spec'), { force: true }); continue; } // built: its spec lives with its code
    fs.writeFileSync(path.join(PL, `${id}.spec`), `# spec_id: eravos.organism.${D.id}.${id} · status MAPPED (specified, not built) · domain ${D.id}
identity:
  id: eravos.${D.id}.${id} ; label: ${label} ; icon: ${icon} ; category: ${D.label}
  folder: ${D.folder}/tools/<category>/${id}/   (tool.json · ${id}.engine.js · ${id}.ui.js · ${id}.spec) — its own pack, never merged into another tool
  purpose: ${purpose}
ports:
  in:
${list(ins.map(p => p + ' — ' + (PORTS[p.split(' ')[0]] || '')))}
  out:
${list(outs.map(p => p + ' — ' + (PORTS[p.split(' ')[0]] || '')))}
params:
${list(params)}
behaviour:
${list(behave)}
depends_on:
  mode: ${D.mode}   units: [${D.units.map(u => u.split(' ')[0]).join(', ')}]
  works_with: [${(works || []).join(', ')}]   # other domains reached only through typed ports / bus events
acceptance (must pass before status → built — nothing pretends to work):
    - ${test}
    - standard: renders/produces output through its out port; unmount leaves zero subscribers, ports, wires; params clamp; presets load
`); n++;
  }
  fs.writeFileSync(path.join(ROOT, 'tools', D.id, 'domain.spec'), `# spec_id: eravos.domain.${D.id} · status ${done.size ? 'BUILDING (' + done.size + ' built: ' + Array.from(done).join(', ') + ')' : 'MAPPED'} · folder ${D.folder}/  (exe: ${D.folder}/ beside ERAVOS.exe)
domain: ${D.icon} ${D.label} — ${D.about}
mode: ${D.mode}
units (toolbar expansion, built only when needed):
${list(D.units)}
tools (each its own folder + spec; mapped ones in planned/):
${list(D.tools.map(t => `${t[2]} ${t[0]} — ${t[3]}  [in: ${t[4].join(', ') || '—'} → out: ${t[5].join(', ')}]`))}
build order: source tools first (they make something to see), then transforms, then exports; one tool per step, each green before the next.
boundary: nothing in ${D.folder}/ is read by the shell or another domain; the shell sees only units, modes, needs, packs.
`);
}
fs.writeFileSync(path.join(OUT, 'eravos.domains.map.spec'), `# spec_id: eravos.domains.map · the map of everything ERAVOS can hold (generated by build/domain-specs.mjs)
shell: blank, domain-free (Start · Add · Options). A domain = a folder + packs. Tools = separate folders. Wires = typed ports.
port types (the only way domains meet):
${list(Object.keys(PORTS).map(k => k + ' — ' + PORTS[k]))}
domains:
    - 🎛 music — BUILT · tools/music/ · ${music.length} tools: ${music.join(', ')}
${DOMAINS.map(D => { const b = builtIn(D.id); return `    - ${D.icon} ${D.id} — ${b.length ? 'BUILDING (' + b.length + ' built: ' + b.join(', ') + ')' : 'MAPPED'} · ${D.folder}/ · ${D.tools.length} tools mapped: ${D.tools.map(t => t[0]).join(', ')}`; }).join('\n')}
cross-domain bridges (a tool in one domain that speaks another's port — never a copy of the other domain):
${list(DOMAINS.flatMap(D => D.tools.filter(t => (t[9] || []).length).map(t => `${D.id}.${t[0]} ↔ ${t[9].join(', ')}`)))}
rule: no domain is a monolith — a domain is only its tools; remove a tool's pack and only that tool is gone.
`);
console.log(`${n} tool specs · ${DOMAINS.length} domain specs · map → specs/eravos.domains.map.spec`);
