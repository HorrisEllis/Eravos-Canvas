#!/usr/bin/env node
/* 3.127 every tool's spec carries its DAG (his words, 2026-11-06: "Map, spec first. Each tool needs a spec with a dag.")
 *   node build/spec-dag.mjs
 * For every tool spec — built (tools/<d>/tools/<cat>/<t>/<t>.spec) and planned (tools/<d>/planned/<t>.spec) — a generated block at the
 * end, replaced on every run (the hand-written spec above it is never touched):
 *   components   what it stands on, layer by layer (a component's own "stands on:" line, if any, puts it a layer higher), built or not
 *   build order  bottom up: every component before the tool, each after what it stands on
 *   shared with  how many other tools stand on each of its components (depth added to one reaches them all)
 *   built tools: in it now (code calls today) · comes out of it (extract from) · planned (a planned spec that extends it)
 * A tool's signal flow (which part feeds which) is hand-written in its spec as "signal_dag:" — the generated block only checks that every
 * node it names is one of the tool's components (or in/out), and reports the ones that are not. */
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), MUSIC = path.join(ROOT, 'tools', 'music');
const CDIR = path.join(MUSIC, 'components'), TDIR = path.join(MUSIC, 'tools'), PDIR = path.join(MUSIC, 'planned');
const MARK = '# ---- dag (generated by build/spec-dag.mjs';
const read = (f) => fs.readFileSync(f, 'utf8');

// components and what each stands on
const comps = {};
for (const id of fs.readdirSync(CDIR).sort()) {
  const spec = path.join(CDIR, id, id + '.spec'); if (!fs.existsSync(spec)) { if (fs.existsSync(path.join(CDIR, id, id + '.js'))) comps[id] = { built: true, on: [] }; continue; }
  const s = read(spec), m = /^\s*stands on:\s*(.+)$/m.exec(s);
  comps[id] = { built: fs.existsSync(path.join(CDIR, id, id + '.js')), on: m ? m[1].split(/[·,]/).map(x => x.trim()).filter(x => x && x !== '—' && x !== 'nothing') : [] };
}
const label = (c) => c + (comps[c] && comps[c].built ? ' ✓' : '');
// the closure of what a set of components stands on, as layers (0 = stands on nothing)
function layers(list) {
  const all = new Set(), add = (c) => { if (all.has(c)) return; all.add(c); ((comps[c] || {}).on || []).forEach(add); }; list.forEach(add);
  const depth = {}, d = (c, seen = new Set()) => { if (depth[c] !== undefined) return depth[c]; if (seen.has(c)) return 0; seen.add(c); const on = ((comps[c] || {}).on || []).filter(x => all.has(x)); return (depth[c] = on.length ? 1 + Math.max(...on.map(x => d(x, seen))) : 0); };
  all.forEach(c => d(c)); const out = []; all.forEach(c => { (out[depth[c]] = out[depth[c]] || []).push(c); }); return out.map(l => (l || []).sort());
}

// who stands on what: planned assembles + built tools' components (data/components-map.js, build/components-map.mjs)
const users = {}; const use = (c, t) => { (users[c] = users[c] || new Set()).add(t); };
const planned = {};
for (const f of fs.readdirSync(PDIR).filter(f => f.endsWith('.spec'))) {
  const s = read(path.join(PDIR, f)), L = s.split('\n'), i = L.findIndex(l => l.startsWith('assembles')), id = 'eravos.' + f.replace(/\.spec$/, '');
  const list = i >= 0 ? L[i + 1].trim().split(' · ').map(x => x.trim()).filter(x => comps[x]) : [];
  planned[id] = { file: path.join(PDIR, f), list }; list.forEach(c => use(c, id));
}
global.window = {}; await import(path.join(MUSIC, 'data', 'components-map.js')); const MC = global.window.MusicComponents || { tools: {} };
Object.entries(MC.tools).forEach(([t, o]) => [].concat(o.uses, o.becomes, o.planned).forEach(c => use(c, t)));

function block(id, list, extra) {
  const ls = layers(list), order = ls.flat(), out = [MARK + ' — the map; re-run after changing assembles or a component spec; nothing above is touched)', 'dag:'];
  if (!list.length) out.push('  components: none shared yet — its code is all its own (as components are built, they show here)');
  else {
    out.push(`  components: ${list.length} it stands on${order.length > list.length ? ` (+${order.length - list.length} they stand on)` : ''} · ${order.filter(c => comps[c] && comps[c].built).length} of ${order.length} built (✓)`);
    ls.forEach((l, i) => out.push(`  layer ${i}: ${l.map(label).join(' · ')}`));
    out.push(`  tool: ${id} ← ${list.join(' + ')}`);
    out.push(`  build order: ${order.map(label).join(' → ')} → ${id.replace(/^eravos\./, '')}`);
    out.push(`  shared with: ${order.map(c => `${c} ${Math.max(0, ((users[c] && users[c].size) || 1) - 1)}`).join(' · ')}  (other tools on each)`);
  }
  (extra || []).forEach(x => out.push('  ' + x));
  return out.join('\n') + '\n';
}
function signalCheck(s, list) {
  const m = /^signal_dag[^\n]*:\n((?:[ \t]+.+\n)+)/m.exec(s); if (!m) return [];
  // the nodes are the component-shaped names (lower-case, hyphenated, or a known component); words around them are prose
  const names = new Set(); for (const x of m[1].matchAll(/\b([a-z][a-z0-9]*(?:-[a-z0-9]+)+|[a-z]+)\b/g)) if (x[1].includes('-') || comps[x[1]]) names.add(x[1]);
  const bad = Array.from(names).filter(n => !list.includes(n)), unused = list.filter(c => !names.has(c));
  return [bad.length ? `signal_dag check: not among its components: ${bad.join(', ')}` : 'signal_dag check: every node is one of its components ✓']
    .concat(unused.length ? [`signal_dag check: components with no place in the flow yet: ${unused.join(', ')}`] : []);
}
function write(file, text) {
  const s = read(file), i = s.indexOf(MARK), base = (i >= 0 ? s.slice(0, i) : s).replace(/\n*$/, '\n\n');
  if (base + text !== s) { fs.writeFileSync(file, base + text); return 1; } return 0;
}
let n = 0, t = 0;
Object.entries(planned).forEach(([id, p]) => { t++; n += write(p.file, block(id, p.list, signalCheck(read(p.file), p.list))); });
for (const cat of fs.readdirSync(TDIR)) { const cd = path.join(TDIR, cat); if (!fs.statSync(cd).isDirectory()) continue;
  for (const tn of fs.readdirSync(cd)) { const td = path.join(cd, tn), tj = path.join(td, 'tool.json'), sf = path.join(td, tn + '.spec'); if (!fs.existsSync(tj) || !fs.existsSync(sf)) continue;
    const id = JSON.parse(read(tj)).id, o = MC.tools[id] || { uses: [], becomes: [], planned: [] }, list = Array.from(new Set([].concat(o.uses, o.becomes, o.planned)));
    t++; n += write(sf, block(id, list, [`in it now: ${o.uses.join(' · ') || '—'}`, `comes out of it: ${o.becomes.join(' · ') || '—'}`, `planned: ${o.planned.join(' · ') || '—'}`].concat(signalCheck(read(sf), list))));
  } }
console.log(`${t} tool specs carry their DAG (${n} changed) · ${Object.keys(comps).length} components`);
