#!/usr/bin/env node
// Writes specs/eravos.structure.map.spec — WHERE EVERYTHING IS, generated from the folders (never edited by hand):
// every domain → its core, its tools by category (with their packs), its cross-tool bundles, its planned tools.
//   node build/structure-map.mjs
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), DOM = path.join(ROOT, 'domains');
const dirs = (d) => fs.existsSync(d) ? fs.readdirSync(d).filter(n => fs.statSync(path.join(d, n)).isDirectory()).sort() : [];
const json = (f) => { try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch (e) { return null; } };
const L = ['# spec_id: eravos.structure.map · GENERATED by build/structure-map.mjs from the folders — do not edit',
  '# Add a tool: node build/new-tool.mjs --domain <d> --category <c> --id <id> --label "<Label>" → node build/index-tools.mjs → node build/validate.mjs',
  '# Add a pack: drop a folder with pack.json into <tool>/packs/ (one tool) or domains/<d>/content/bundles/ (several tools) → node build/index-tools.mjs',
  '# Add a domain: copy templates/domain/ to domains/<id>/ and add <id> to domains/index.js', ''];
let nTools = 0, nPacks = 0, nItems = 0;
for (const d of dirs(DOM)) {
  const dj = json(path.join(DOM, d, 'domain.json')) || {};
  const tools = path.join(DOM, d, 'tools');
  L.push(`domains/${d}/   ${dj.icon || ''} ${dj.label || d}${fs.existsSync(path.join(DOM, d, 'domain.js')) ? '' : '   (MAPPED — specs only)'}`);
  if (fs.existsSync(path.join(DOM, d, 'core'))) L.push(`  core/            ${fs.readdirSync(path.join(DOM, d, 'core')).filter(f => !f.startsWith('.')).join(' · ')}`);
  for (const c of dirs(tools)) {
    const cj = json(path.join(tools, c, 'category.json')) || {}, ts = dirs(path.join(tools, c)).filter(t => fs.existsSync(path.join(tools, c, t, 'tool.json')));
    if (!ts.length) continue;
    L.push(`  tools/${c}/   (${cj.label || c})`);
    for (const t of ts) {
      const m = json(path.join(tools, c, t, 'tool.json')), pd = path.join(tools, c, t, 'packs'); nTools++;
      const packs = dirs(pd).map(p => { const pk = json(path.join(pd, p, 'pack.json')); if (!pk) return null; const n = Object.values(pk.items || {}).reduce((a, k) => a + Object.values(k).reduce((b, x) => b + (Array.isArray(x) ? 1 : Object.keys(x).length), 0), 0); nPacks++; nItems += n; return `${p} (${n})`; }).filter(Boolean);
      L.push(`    ${t}/   ${m.icon || ''} ${m.label} · ${m.id} · ${Object.values(m.files).flat().join(' · ')}${packs.length ? '\n        packs/ ' + packs.join(' · ') : ''}`);
    }
  }
  const bd = path.join(DOM, d, 'content', 'bundles');
  if (fs.existsSync(bd)) L.push(`  content/bundles/   ${dirs(bd).map(b => { const pk = json(path.join(bd, b, 'pack.json')); nPacks++; return `${b} → ${pk ? [].concat(pk.for).length + ' tools' : '?'}`; }).join(' · ')}`);
  const pl = path.join(DOM, d, 'planned');
  if (fs.existsSync(pl)) L.push(`  planned/   ${fs.readdirSync(pl).filter(f => f.endsWith('.spec')).map(f => f.replace(/\.spec$/, '')).join(' · ')}   (specs of tools not built yet)`);
  L.push('');
}
L.push(`# totals: ${nTools} tools · ${nPacks} packs · ${nItems} items inside tool packs`);
fs.writeFileSync(path.join(ROOT, 'specs', 'eravos.structure.map.spec'), L.join('\n') + '\n');
console.log(`structure map: ${nTools} tools · ${nPacks} packs`);
