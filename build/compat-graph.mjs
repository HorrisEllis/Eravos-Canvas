#!/usr/bin/env node
/* CG2 — the compatibility graph from the component contracts (specs/eravos.compat-graph.spec). Reads every
 * tools/<d>/components/<id>/<id>.contract.json and tools/<d>/types.json, builds the graph with tools/core/compat/compat.js (pure), and writes
 * docs/compat-graph.md: siblings (components that fill the same slot — swappable), bridges used, how many components can feed each.
 *   node build/compat-graph.mjs            write the report
 *   node build/compat-graph.mjs --check    exit 1 if the report is out of date */
import fs from 'fs'; import path from 'path'; import { createRequire } from 'module'; import { fileURLToPath } from 'url';
const require = createRequire(import.meta.url), ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const Compat = require(path.join(ROOT, 'tools/core/compat/compat.js'));
export function load(domain = 'music') {
  const base = path.join(ROOT, 'tools', domain), types = JSON.parse(fs.readFileSync(path.join(base, 'types.json'), 'utf8')), contracts = [];
  for (const id of fs.readdirSync(path.join(base, 'components')).sort()) { const f = path.join(base, 'components', id, id + '.contract.json'); if (fs.existsSync(f)) contracts.push(JSON.parse(fs.readFileSync(f, 'utf8'))); }
  return { types, contracts };
}
function report() {
  const { types, contracts } = load(), G = Compat.graph(contracts, types);
  const feeds = {}; G.edges.forEach(e => { const b = e.to.split('.')[0]; feeds[b] = (feeds[b] || new Set()).add(e.from.split('.')[0]); });
  const L = ['# The compatibility graph (CG2) — generated by `node build/compat-graph.mjs`; do not edit', '',
    `${contracts.length} components with a contract · ${G.edges.length} port-to-port connections that fit · ${G.siblings.length} slots with more than one component (swappable)`, '',
    '## Siblings — components that fill the same slot (a mutation can SWAP one for another)', '', '| slot (ports) | components |', '|---|---|',
    ...G.siblings.map(s => `| \`${s.slot}\` | ${s.components.join(' · ')} |`), '',
    '## Stand-ins — what can replace each component (it has every port the other has; extra inputs idle)', '', '| component | can be swapped for |', '|---|---|',
    ...Object.keys(G.standIns).sort().map(k => `| ${k} | ${G.standIns[k].join(' · ')} |`), '',
    '## Bridges used (an adapter the graph may insert; shown, never hidden)', '', '| bridge | connections |', '|---|---|',
    ...Object.keys(G.bridges).sort().map(k => `| ${k} | ${G.bridges[k]} |`), '',
    '## What can feed each component', '', '| component | kind | slot | fed by (components) |', '|---|---|---|---|',
    ...G.nodes.map(n => `| ${n.id} | ${n.kind} | \`${n.slot}\` | ${feeds[n.id] ? feeds[n.id].size : 0} |`), ''];
  return L.join('\n');
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const out = path.join(ROOT, 'docs', 'compat-graph.md'), text = report();
  if (process.argv.includes('--check')) { const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : ''; if (cur !== text) { console.error('docs/compat-graph.md is out of date: node build/compat-graph.mjs'); process.exit(1); } console.log('✓ compat graph up to date'); }
  else { fs.writeFileSync(out, text); console.log('wrote docs/compat-graph.md'); }
}
