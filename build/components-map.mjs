#!/usr/bin/env node
/* 3.126 the components each tool is made of → tools/music/data/components-map.js (window.MusicComponents), for the tool page's
 * Components tab (his words, 2026-11-06: "Each tool with each component/ui/packs/mod/suite/etc all with a clear line of seperation
 * all added to the tool page"). Read from the code and the specs, never by hand:
 *   uses     — built components the tool's code calls today (MusicParts.<fn> → the component that exports fn)
 *   becomes  — components its spec says will be extracted from it ("extract from: <tool>")
 *   planned  — components a planned spec that extends this tool assembles ("built_today (read from …, eravos.<tool> …)")
 * node build/components-map.mjs */
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), MUSIC = path.join(ROOT, 'tools', 'music');
const CDIR = path.join(MUSIC, 'components'), TDIR = path.join(MUSIC, 'tools'), PDIR = path.join(MUSIC, 'planned');
const read = (f) => fs.readFileSync(f, 'utf8');
const field = (txt, k) => { const m = new RegExp('^\\s*' + k + ':\\s*(.+)$', 'm').exec(txt); return m ? m[1].trim() : ''; };

// components: id, group, job, built, exported functions, where it is extracted from
const comps = {}, fnOf = {};
for (const id of fs.readdirSync(CDIR).sort()) {
  const dir = path.join(CDIR, id); if (!fs.statSync(dir).isDirectory()) continue;
  const spec = fs.existsSync(path.join(dir, id + '.spec')) ? read(path.join(dir, id + '.spec')) : '', js = path.join(dir, id + '.js');
  const ident = field(spec, 'id'), group = (/group:\s*([\w-]+)/.exec(ident) || [])[1] || '';
  const from = (field(spec, 'extract from').split('(')[0] || '').trim().split(/\s+/)[0] || '';
  comps[id] = { label: id.replace(/-/g, ' '), group, job: field(spec, 'job'), built: fs.existsSync(js), from: from && !/\.js$/.test(from) ? 'eravos.' + from : '' };
  if (fs.existsSync(js)) { const src = read(js), m = /Object\.assign\(root\.MusicParts,\s*\{([^}]*)\}/.exec(src);   // both ways a component exports
    if (m) m[1].split(',').map(s => s.trim().split(':')[0].trim()).filter(Boolean).forEach(fn => { fnOf[fn] = id; });
    for (const x of src.matchAll(/root\.MusicParts\.(\w+)\s*=/g)) fnOf[x[1]] = id; }
}
// built tools: which component functions their code calls
const tools = {};
const add = (t, k, c) => { const o = tools[t] = tools[t] || { uses: [], becomes: [], planned: [] }; if (!o[k].includes(c)) o[k].push(c); };
for (const cat of fs.readdirSync(TDIR)) { const cd = path.join(TDIR, cat); if (!fs.statSync(cd).isDirectory()) continue;
  for (const t of fs.readdirSync(cd)) { const td = path.join(cd, t); if (!fs.existsSync(path.join(td, 'tool.json'))) continue;
    const id = JSON.parse(read(path.join(td, 'tool.json'))).id;
    fs.readdirSync(td).filter(f => f.endsWith('.js') && !f.endsWith('.test.js')).forEach(f => { for (const m of read(path.join(td, f)).matchAll(/\b(?:MusicParts|MP)\.(\w+)/g)) if (fnOf[m[1]]) add(id, 'uses', fnOf[m[1]]); });
  } }
Object.entries(comps).forEach(([c, x]) => { if (x.from) add(x.from, 'becomes', c); });
// planned specs that extend a built tool: the components they assemble
for (const f of fs.readdirSync(PDIR).filter(f => f.endsWith('.spec'))) {
  const s = read(path.join(PDIR, f)), m = /built_today \(read from [^,]+,\s*(eravos\.[\w-]+)/.exec(s); if (!m) continue;
  const lines = s.split('\n'), i = lines.findIndex(l => l.startsWith('assembles')); if (i < 0) continue;
  lines[i + 1].trim().split(' · ').map(x => x.trim()).filter(x => comps[x]).forEach(c => add(m[1], 'planned', c));
}
Object.values(tools).forEach(o => { o.becomes = o.becomes.filter(c => !o.uses.includes(c)); o.planned = o.planned.filter(c => !o.uses.includes(c) && !o.becomes.includes(c)); });
const out = `/* generated by build/components-map.mjs — do not edit (the code and the specs are the source) */\nwindow.MusicComponents = ${JSON.stringify({ components: comps, tools }, null, 0)};\n`;
fs.writeFileSync(path.join(MUSIC, 'data', 'components-map.js'), out);
const n = Object.keys(tools).length, u = Object.values(tools).filter(o => o.uses.length).length;
console.log(`${Object.keys(comps).length} components (${Object.values(comps).filter(c => c.built).length} built) · ${n} tools with components · ${u} use a built one today`);
