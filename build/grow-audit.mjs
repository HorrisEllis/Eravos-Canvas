#!/usr/bin/env node
/* P49.3 growth audit — node build/grow-audit.mjs → specs/eravos.growth.spec (generated; measured, no model).
 * James, 2026-10-22: "Windows that grow (keyboards up to 88 keys) not just paino." (and 10-21: "anything else that can be expanded per tool")
 * Clear Glass's driver opens every music tool's window small (520 × 520) and big (1400 × 1000), and counts what its face shows: every
 * element, keys, steps/cells (buttons and grid cells), canvases and their drawn pixels. Grows = more things shown when bigger.
 * Stretches = the same things, only larger. A tool that stretches is a candidate for P49.3.<tool>. What its range is (steps, pads,
 * channels, bars…) is read from its code in that phase: this audit only says who does not grow yet. */
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
import { chromium } from '../host/driver/glass.js';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const p = await b.newPage({ viewport: { width: 1700, height: 1200 } });
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.addInitScript(() => { window.ERAVOS_CATALOG_ALL = true; });
await p.goto('file://' + ROOT + '/canvas/index.html?noboot');
await p.waitForFunction(() => window.OrganismFactory && window.Shell && window.CanvasWM && OrganismFactory.defined().length > 40, null, { timeout: 30000 });
const rows = await p.evaluate(async () => {
  Shell.activate(); try { Shell.X.enterMode('music'); } catch (e) {}
  const frames = async (n) => { for (let i = 0; i < n; i++) await new Promise(r => requestAnimationFrame(r)); };
  const count = (win) => {
    const body = win.querySelector('.wm-body'); const q = (s) => body.querySelectorAll(s).length;
    const cv = Array.from(body.querySelectorAll('canvas')).filter(c => !c.closest('.lk-strip'));
    return { all: body.querySelectorAll('*').length, keys: q('.uk-key'), knobs: q('.uk-knob'), cells: q('button, [data-step], [data-pad], [data-n], [data-ch], [role=gridcell]'),
      canvases: cv.length, canvasPx: cv.reduce((a, c) => a + c.width * c.height, 0), bodyW: body.clientWidth };
  };
  const out = [];
  for (const d of OrganismFactory.defined().filter(x => x.domain === 'music' && !x.hidden)) {
    OrganismFactory.clearAll(Kernel); CanvasWM.view = { x: 0, y: 0, z: 1 }; CanvasWM.applyView();
    const id = OrganismFactory.spawn(d.id, { x: 10, y: 10 }); if (!id) { out.push({ id: d.id, label: d.label, err: 'did not open' }); continue; }
    await frames(4); const win = CanvasWM.windowOf(id); if (!win) { out.push({ id: d.id, label: d.label, err: 'no window' }); continue; }
    Object.assign(win.style, { width: '520px', height: '520px' }); await frames(6); await new Promise(r => setTimeout(r, 120)); const small = count(win);
    Object.assign(win.style, { width: '1400px', height: '1000px' }); await frames(6); await new Promise(r => setTimeout(r, 120)); const big = count(win);
    out.push({ id: d.id, label: d.label, category: d.category || '', small, big });
    OrganismFactory.close(id);
  }
  return out;
});
await b.close();
const verdict = (r) => {
  if (r.err) return 'not measured — ' + r.err;
  const s = r.small, g = r.big;
  if (g.keys > s.keys) return `GROWS (keys ${s.keys} → ${g.keys})`;
  if (g.cells > s.cells || g.all > s.all + 2) return `GROWS (things shown ${s.all} → ${g.all}, cells ${s.cells} → ${g.cells})`;
  if (g.canvasPx > s.canvasPx * 1.5) return `STRETCHES — the same ${s.all} things; its ${s.canvases} display(s) draw bigger (${Math.round(s.canvasPx / 1000)}k → ${Math.round(g.canvasPx / 1000)}k px)`;
  return `STRETCHES — the same ${s.all} things, only larger`;
};
const grows = rows.filter(r => /^GROWS/.test(verdict(r))), stretch = rows.filter(r => /^STRETCHES/.test(verdict(r))), other = rows.filter(r => !/^(GROWS|STRETCHES)/.test(verdict(r)));
const line = (r) => `  ${r.label} (${r.id})${r.category ? ' · ' + r.category : ''}: ${verdict(r)}`;
const out = `# spec_id: eravos.growth · GENERATED by build/grow-audit.mjs on ${new Date().toISOString().slice(0, 10)} — do not edit; rerun it
# map: eravos.phase49-map P49.3 · James, 2026-10-22: "Windows that grow (keyboards up to 88 keys) not just paino."
# Measured with Clear Glass's driver: each music tool's window at 520 × 520, then at 1400 × 1000. GROWS = it shows more things when
# bigger. STRETCHES = the same things, larger, which makes it a candidate. What a tool's range is (steps, pads, channels, bars,
# octaves…) is read from its code in its own phase. A display that draws more pixels is counted as stretching: its range may
# already follow its size (Spectrum does), and that is checked per tool.

## Grows already (${grows.length})
${grows.map(line).join('\n') || '  none'}

## Stretches — candidates for P49.3.<tool> (${stretch.length})
${stretch.map(line).join('\n') || '  none'}
${other.length ? `\n## Not measured (${other.length})\n${other.map(line).join('\n')}\n` : ''}`;
fs.writeFileSync(path.join(ROOT, 'specs', 'eravos.growth.spec'), out);
console.log(`${rows.length} tools · ${grows.length} grow · ${stretch.length} stretch · ${other.length} not measured → specs/eravos.growth.spec`);
if (errs.length) console.log('page errors:', errs.slice(0, 3));
