#!/usr/bin/env node
/* Give every planned tool spec (tools/<d>/planned/*.spec) the same dependency block a built tool gets:
 *   node build/planned-deps.mjs     (needs Playwright; asks the running Shell.X.deps(), like build/specs.mjs)
 * - the spec's "hooks:" line is read into hook contracts (STD.* builders, note_out, audio_in, data_out, …)
 * - those hooks go through the same resolvers the Add menu uses → mode, toolbar units, services, works_with
 * - a spec whose tool the domain generator already maps (it has "depends_on:") is left alone
 * The block is replaced on every run; the hand-written part of the spec is never touched. */
import { chromium } from 'playwright';
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MARK = '# ---- dependencies (generated by build/planned-deps.mjs';

// ---------------------------------------------------------------- the hooks line → hook contracts
const STD = {
  note_in: ['in', 'event_bus', 'note:trigger'], note_out: ['out', 'event_bus', 'note:trigger'],
  midi_in: ['in', 'event_bus', 'midi:note'], theory_in: ['in', 'event_bus', 'theory:key-change'],
  theory_out: ['out', 'event_bus', 'theory:key-change'], transport_in: ['in', 'event_bus', 'transport:tick|transport:play|transport:stop'],
  audio_in: ['in', 'audio'], audio_out: ['out', 'audio'], mod_in: ['in', 'modulation'], mod_out: ['out', 'modulation'],
  control_in: ['in', 'modulation'], control_out: ['out', 'modulation'],
  data_in: ['in', 'dataflow'], data_out: ['out', 'dataflow'], trigger_in: ['in', 'dataflow'], trigger_out: ['out', 'dataflow'],
  asset_in: ['in', 'event_bus', 'asset:ready'], asset_out: ['out', 'event_bus', 'asset:ready'],
};
function splitTop(s) {   // split on ';' outside parentheses
  const out = []; let depth = 0, cur = '';
  for (const ch of s) { if (ch === '(') depth++; if (ch === ')') depth = Math.max(0, depth - 1); if (ch === ';' && !depth) { out.push(cur); cur = ''; } else cur += ch; }
  return out.concat(cur).map(x => x.trim()).filter(Boolean);
}
const dirX0 = (paren) => (paren.match(/^\s*(in|out)\b/) || [])[1];
function parseHooks(line, prefix) {
  prefix = (line.match(/\b([a-z]+)\.hook\./) || [])[1] || prefix;   // the spec's own hook prefix wins
  const hooks = [], notes = [], seen = new Set();
  const add = (base, dir, wire, event, port) => {
    let id = `${prefix}.hook.${base}`; for (let i = 2; seen.has(id); i++) id = `${prefix}.hook.${base}_${i}`; seen.add(id);
    hooks.push({ hook_id: id, direction: dir, wire_type: wire, event_type: event || (wire === 'event_bus' ? 'event' : wire), port: wire === 'event_bus' ? undefined : port });
  };
  for (const seg of splitTop(line)) {
    let flat = seg; while (/\([^()]*\([^()]*\)/.test(flat)) flat = flat.replace(/\(([^()]*)\(([^()]*)\)/, '($1[$2]');   // nested → one level
    const paren = (flat.match(/\(([^)]*)\)/) || [])[1] || '', head = flat.replace(/\([^)]*\)/g, ' ').trim();
    if (/generated from exposed ports/.test(seg)) { notes.push('ports are generated from the exposed ports of the wrapped flow'); continue; }
    if (/\bper [a-z]/.test(seg)) notes.push(`${seg.replace(/\s+/g, ' ')} — one port each`);
    const std = head.match(/STD\.(\w+)/), names = head.replace(/STD\.\w+/, '').split(',').map(x => x.trim().split(/\s+/)).filter(w => w[0]);
    let kind = std ? std[1] : null;
    // "asset in/out", "asset output", "asset in"
    if (!kind && /^asset\b/.test(head)) { if (/in\b/.test(head)) add('asset_in', 'in', 'event_bus', 'asset:ready'); if (/out/.test(head)) add('asset_out', 'out', 'event_bus', 'asset:ready'); continue; }
    // explicit contract: (in ; audio ; port x) · (out ; note:trigger 2.0.0) · (modulation) · (voice:analysis …)
    const wireX = dirX0(paren) && (paren.match(/;\s*(audio|modulation|dataflow)\b/) || [])[1], dirX = dirX0(paren), evX = (paren.match(/\b([a-z]+:[a-z_-]+)/) || [])[1], portX = (paren.match(/port (\w+)/) || [])[1];
    const list = names.length ? names : [[kind || 'hook']];
    for (const w of list) {
      let word = w[0].replace(/^[a-z]+\.hook\./, ''), arg = w[1] && !/^(per|or|for|to|incl)$/.test(w[1]) ? w[1].replace(/\W/g, '') : '';
      const k = kind && (!names.length || /^[a-z_]+$/.test(word)) ? (STD[kind] ? kind : null) : null;
      let def = STD[k] || STD[word] || null, base = word;
      if (!def && /_(in|out)$/.test(word)) {   // print_out, apply_out, analysis_out, pitch_out, mod_position …
        const dir = word.endsWith('_in') ? 'in' : 'out';
        def = paren.includes('modulation') ? [dir, 'modulation'] : evX ? [dir, 'event_bus', evX] : [dir, 'dataflow'];
      }
      if (!def && /^mod_/.test(word)) def = STD.mod_in;
      if (!def) { notes.push(`unparsed hook: ${seg}`); continue; }
      let [dir, wire, ev] = def;
      if (dirX) dir = dirX;
      if (wire === 'event_bus' && evX && !/^(note|midi|theory|transport)/.test(kind || '')) ev = evX;
      if (wireX) wire = wireX; else if (wire === 'audio' && paren.includes('modulation')) wire = 'modulation';
      if (wireX && wire !== 'event_bus') ev = undefined;
      const named = !STD[word] && /_(in|out)$/.test(word) ? word.replace(/_(in|out)$/, '') : '';
      const port = portX || arg || (wire === 'modulation' && /^mod_/.test(word) ? 'mod.' + word.slice(4) : named || (dir === 'in' ? 'in' : 'out'));
      if (/^mod_/.test(word) && wire === 'modulation' && dir === 'in') base = word;
      if (arg && /^(data|trigger|control)_/.test(word)) base = `${arg}_${dir}`;   // data_out matches → matches_out
      add(base, dir, wire, ev, port);
    }
  }
  return { hooks, notes };
}

// ---------------------------------------------------------------- every planned spec without a domain-generated depends_on
const files = [];
for (const d of fs.readdirSync(path.join(ROOT, 'tools'))) {
  const dir = path.join(ROOT, 'tools', d, 'planned'); if (!fs.existsSync(dir)) continue;
  fs.readdirSync(dir).filter(f => f.endsWith('.spec')).forEach(f => files.push({ domain: d, file: path.join(dir, f) }));
}
const todo = files.map(({ domain, file }) => {
  const src = fs.readFileSync(file, 'utf8'), body = src.split(MARK)[0];
  if (/^depends_on:/m.test(body)) return null;
  const hl = body.split('\n').filter(l => /^hooks:/.test(l)).map(l => l.replace(/^hooks:\s*/, '')).join(' ; ');
  const id = (body.match(/\bid: ([\w.-]+)/) || [])[1] || `eravos.${domain}.${path.basename(file, '.spec')}`;
  const category = (body.match(/· category ([\w-]+)/) || [])[1] || null;
  const prefix = path.basename(file, '.spec').split('-').map(w => w.slice(0, 3)).join('').slice(0, 6);
  const { hooks, notes } = parseHooks(hl, prefix);
  return { file, body, desc: { id, domain, category, hooks, permissions: [] }, notes };
}).filter(Boolean);

const b = await chromium.launch(); const p = await b.newPage();
await p.addInitScript(() => { window.ERAVOS_CATALOG_ALL = true; });   // P41 catalog: a fresh profile installs no tools — this script needs every one
await p.goto('file://' + ROOT + '/canvas/index.html?noboot'); await p.waitForFunction(() => window.Shell && window.Shell.X);
const res = await p.evaluate((descs) => descs.map(d => { const r = Shell.X.deps(d); return { mode: r.mode, modeLabel: r.modeLabel, units: r.units, services: r.services, inputs: r.inputs, outputs: r.outputs, works_with: r.works_with }; }), todo.map(t => t.desc));
const unitL = await p.evaluate(() => Object.fromEntries(Shell.X.units().map(u => [u.id, u.label])));
await b.close();

todo.forEach((t, i) => {
  const D = res[i], L = [MARK + ' from the hooks line above — do not edit by hand)', 'dependencies:   # planned: what this tool will need once built',
    `  mode: ${D.mode || 'none'}${D.modeLabel ? '   # ' + D.modeLabel : ''}`,
    `  toolbar_units: [${D.units.join(', ')}]   # ui expansion when added: ${D.units.map(u => unitL[u] || u).join(' · ') || 'none'}`,
    '  services:'].concat(D.services.map(s => `    - ${s.id}: ${s.label}${s.why ? ' — ' + s.why : ''}`));
  L.push('  inputs:'); D.inputs.forEach(h => L.push(`    - ${h.hook} (${h.kind}${h.port ? ' · port ' + h.port : ''})${h.ambient ? ' — ambient broadcast' : ''}`));
  L.push('  outputs:'); D.outputs.forEach(h => L.push(`    - ${h.hook} (${h.kind}${h.port ? ' · port ' + h.port : ''})`));
  L.push(`  works_with: [${D.works_with.join(', ')}]`);
  t.notes.forEach((n, j) => L.push((j ? '' : '  notes:\n') + '    - ' + n));
  fs.writeFileSync(t.file, t.body.replace(/\s*$/, '\n\n') + L.join('\n') + '\n');
});
const unparsed = todo.flatMap(t => t.notes.filter(n => n.startsWith('unparsed')).map(n => path.relative(ROOT, t.file) + ': ' + n));
console.log(`${todo.length} planned specs given a dependency block` + (unparsed.length ? `\n${unparsed.join('\n')}` : ''));
